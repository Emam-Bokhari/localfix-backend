/**
 * Normalize a US state name or 2-letter abbreviation to Checkr's expected 2-letter uppercase code.
 */
export const normalizeUsStateCode = (state?: string): string | undefined => {
  if (!state) return undefined;
  const trimmed = state.trim();
  if (/^[A-Za-z]{2}$/.test(trimmed)) {
    return trimmed.toUpperCase();
  }
  return US_STATE_MAP[trimmed.toLowerCase()];
};

